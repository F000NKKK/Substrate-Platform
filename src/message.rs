//! Messages for the user: an English template with `{name}` placeholders —
//! the key the UI's translation catalogs use — and the values to put in.
//! Everything Substrate says to a user is one of these, so the UI shows it
//! in the user's language by default (`errorText` / `t(text, args)`).
//!
//! The templates are declared once, in their module's [`messages!`] block;
//! the UI gets them generated (`substrate-messages` writes
//! `ui/src/infra/host/host.generated.ts`), never retyped.

use serde::Serialize;
use std::collections::BTreeMap;
use std::fmt;

/// The template of text that isn't ours to translate: a tool's own output.
pub const VERBATIM: &str = "{detail}";
/// [`VERBATIM`]'s placeholder.
const DETAIL: &str = "detail";

#[derive(Debug, Clone, PartialEq, Eq, Serialize)]
pub struct Message {
    pub text: &'static str,
    #[serde(skip_serializing_if = "BTreeMap::is_empty")]
    pub args: BTreeMap<&'static str, String>,
}

impl Message {
    pub fn new(text: &'static str) -> Self {
        Self {
            text,
            args: BTreeMap::new(),
        }
    }

    /// With `{name}` set to `value`.
    pub fn arg(mut self, name: &'static str, value: impl ToString) -> Self {
        self.args.insert(name, value.to_string());
        self
    }

    /// `detail` as it is (a tool's own words).
    pub fn verbatim(detail: impl ToString) -> Self {
        Self::new(VERBATIM).arg(DETAIL, detail)
    }
}

/// The English text, placeholders filled (logs, a terminal).
impl fmt::Display for Message {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        let mut text = self.text.to_string();
        for (name, value) in &self.args {
            text = text.replace(&format!("{{{name}}}"), value);
        }
        f.write_str(&text)
    }
}

impl From<std::io::Error> for Message {
    fn from(e: std::io::Error) -> Self {
        Self::verbatim(e)
    }
}

/// Declares a module's message templates: `messages! { group { NAME = "text", … } }`
/// — a `pub const` each, and `ALL` (group, name, text) for the export.
#[macro_export]
macro_rules! messages {
    ($group:ident { $( $(#[$doc:meta])* $name:ident = $text:expr ),* $(,)? }) => {
        $( $(#[$doc])* pub const $name: &str = $text; )*
        /// Every template here, for the UI's generated copy.
        pub const ALL: &[(&str, &str, &str)] = &[ $( (stringify!($group), stringify!($name), $name) ),* ];
    };
}

/// Every template Substrate declares, for the export.
pub fn catalog() -> Vec<(&'static str, &'static str, &'static str)> {
    let groups: &[&[(&str, &str, &str)]] = &[
        #[cfg(feature = "git")]
        crate::git::messages::ALL,
        #[cfg(feature = "project")]
        crate::project::messages::ALL,
        crate::process::ALL,
        #[cfg(feature = "terminal")]
        crate::terminal::messages::ALL,
        crate::workspace::ALL,
    ];
    groups.concat()
}

/// The templates as a TypeScript module: `messages.<group>.<name>`.
pub fn typescript() -> String {
    let mut out = String::from(
        "// Generated by substrate-platform (`cargo run --bin substrate-messages`) — don't edit.\n\n/** Substrate's message templates: the i18n catalogs' keys for what the backend says. */\nexport const messages = {\n",
    );
    let mut groups: Vec<&str> = catalog().iter().map(|(g, _, _)| *g).collect();
    groups.dedup();
    for group in groups {
        out.push_str(&format!("  {group}: {{\n"));
        for (_, name, text) in catalog().iter().filter(|(g, _, _)| *g == group) {
            out.push_str(&format!("    {}: {text:?},\n", camel(name)));
        }
        out.push_str("  },\n");
    }
    out.push_str(&format!("}} as const;\n\n/** The host plugin's name: its commands are `plugin:<this>|<command>`. */\nexport const plugin = {:?};\n\n/** The events Substrate's host sends its UI. */\nexport const events = {{\n", crate::events::PLUGIN));
    for (name, event) in crate::events::ALL {
        out.push_str(&format!("  {name}: {event:?},\n"));
    }
    out.push_str("} as const;\n");
    out
}

fn camel(name: &str) -> String {
    let mut out = String::new();
    for (i, word) in name.split('_').enumerate() {
        let lower = word.to_lowercase();
        if i == 0 {
            out.push_str(&lower);
        } else {
            out.push_str(&lower[..1].to_uppercase());
            out.push_str(&lower[1..]);
        }
    }
    out
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn fills_placeholders_for_display() {
        let m = Message::new("{path} already exists").arg("path", "/a");
        assert_eq!(m.to_string(), "/a already exists");
        assert_eq!(Message::verbatim("raw").to_string(), "raw");
    }

    #[test]
    fn names_turn_camel_case() {
        assert_eq!(camel("NOT_A_REPOSITORY"), "notARepository");
    }
}
