//! The plugin's commands — the one list of them, by feature — and their
//! permissions: Tauri's own per command, and the default set (every command)
//! written from the same list.

/// Always there.
const CORE: &[&str] = &["open_url", "open_path", "reveal_path"];

/// Feature `git`: Source Control.
const GIT: &[&str] = &[
    "git_status",
    "git_stage",
    "git_unstage",
    "git_discard",
    "git_commit",
    "git_last_message",
    "git_diff_texts",
    "git_head_text",
    "git_log",
    "git_commit_files",
    "git_branches",
    "git_switch",
    "git_branch_create",
    "git_branch_delete",
    "git_remote",
    "git_integrate",
    "git_operation",
    "git_clone",
    "git_init",
    "git_stash_list",
    "git_stash_push",
    "git_stash_op",
    "git_config_get",
    "git_config_set",
];

/// The default permission set: what a product grants by `substrate:default`.
const DEFAULT_PERMISSIONS: &str = "permissions/default.toml";

/// Every group's commands. Their permissions don't depend on the features
/// a build turns on: the generated files stay the same whoever builds, and
/// granting a command that isn't compiled in allows nothing.
/// Feature `terminal`: shell sessions.
const TERMINAL: &[&str] = &["terminal_shells", "terminal_spawn", "terminal_write", "terminal_resize", "terminal_kill"];

const GROUPS: &[&[&str]] = &[CORE, GIT, TERMINAL];

fn main() {
    let commands: &'static [&'static str] = Box::leak(GROUPS.concat().into_boxed_slice());
    let allows: Vec<String> = commands.iter().map(|c| format!("  \"allow-{}\",", c.replace('_', "-"))).collect();
    let text = format!(
        "# Generated by build.rs from its commands — don't edit.\n[default]\ndescription = \"Every command Substrate's UI calls.\"\npermissions = [\n{}\n]\n",
        allows.join("\n")
    );
    if std::fs::read_to_string(DEFAULT_PERMISSIONS).ok().as_deref() != Some(text.as_str()) {
        std::fs::write(DEFAULT_PERMISSIONS, text).expect("permissions/ is writable");
    }
    tauri_plugin::Builder::new(commands).build();
}
