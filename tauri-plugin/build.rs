//! The plugin's permissions: Tauri's own per command, and the default set
//! (every command) — from Substrate's domains (`substrate_platform::commands`),
//! the one list of its commands, whatever features a build turns on.

use substrate_platform::commands::{SUBSTRATE, names};

/// The default permission set: what a product grants by `substrate:default`.
const DEFAULT_PERMISSIONS: &str = "permissions/default.toml";

fn main() {
    let commands: &'static [&'static str] = Box::leak(names(SUBSTRATE).into_boxed_slice());
    let allows: Vec<String> = commands.iter().map(|c| format!("  \"allow-{}\",", c.replace('_', "-"))).collect();
    let text = format!(
        "# Generated by build.rs from Substrate's domains — don't edit.\n[default]\ndescription = \"Every command Substrate's UI calls.\"\npermissions = [\n{}\n]\n",
        allows.join("\n")
    );
    if std::fs::read_to_string(DEFAULT_PERMISSIONS).ok().as_deref() != Some(text.as_str()) {
        std::fs::write(DEFAULT_PERMISSIONS, text).expect("permissions/ is writable");
    }
    tauri_plugin::Builder::new(commands).build();
}
