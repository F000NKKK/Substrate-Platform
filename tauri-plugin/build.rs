//! The plugin's commands — the one list of them — and their permissions:
//! Tauri's own per command, and the default set (every command) written
//! from the same list.

const COMMANDS: &[&str] = &[
    "git_status",
    "git_stage",
    "git_unstage",
    "git_discard",
    "git_commit",
    "git_last_message",
    "git_diff_texts",
    "git_head_text",
    "git_log",
    "git_commit_files",
    "git_branches",
    "git_switch",
    "git_branch_create",
    "git_branch_delete",
    "git_remote",
    "git_integrate",
    "git_operation",
    "git_clone",
    "git_init",
    "git_stash_list",
    "git_stash_push",
    "git_stash_op",
    "git_config_get",
    "git_config_set",
];

/// The default permission set: what a product grants by `substrate:default`.
const DEFAULT_PERMISSIONS: &str = "permissions/default.toml";

fn main() {
    let allows: Vec<String> = COMMANDS.iter().map(|c| format!("  \"allow-{}\",", c.replace('_', "-"))).collect();
    let text = format!(
        "# Generated by build.rs from its COMMANDS — don't edit.\n[default]\ndescription = \"Every command Substrate's UI calls.\"\npermissions = [\n{}\n]\n",
        allows.join("\n")
    );
    if std::fs::read_to_string(DEFAULT_PERMISSIONS).ok().as_deref() != Some(text.as_str()) {
        std::fs::write(DEFAULT_PERMISSIONS, text).expect("permissions/ is writable");
    }
    tauri_plugin::Builder::new(COMMANDS).build();
}
